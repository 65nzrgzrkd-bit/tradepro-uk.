import assert from 'node:assert/strict';
import { lifecycleEvent } from './lifecycle-event.mjs';
let n=0;const check=fn=>{fn();n++;};
const e={type:'checkout.session.completed',created:100,data:{object:{mode:'subscription',payment_status:'unpaid',customer_email:' Test@Example.invalid ',customer:'cus_fixture',subscription:'sub_fixture'}}};
check(()=>assert.equal(lifecycleEvent(e).p_kind,'checkout_pending'));
check(()=>assert.equal(lifecycleEvent(e).p_email,'test@example.invalid'));
const paid=structuredClone(e);paid.data.object.payment_status='paid';
check(()=>assert.equal(lifecycleEvent(paid).p_kind,'checkout_paid'));
paid.type='checkout.session.async_payment_succeeded';check(()=>assert.equal(lifecycleEvent(paid).p_kind,'checkout_paid'));
paid.data.object.payment_status='unpaid';check(()=>assert.throws(()=>lifecycleEvent(paid)));
const unrelated=structuredClone(e);unrelated.data.object.mode='payment';check(()=>assert.equal(lifecycleEvent(unrelated),null));
check(()=>assert.equal(lifecycleEvent({type:'charge.refunded'}),null));
const missingTime=structuredClone(e);delete missingTime.created;check(()=>assert.throws(()=>lifecycleEvent(missingTime)));
const sub={type:'customer.subscription.updated',created:200,data:{object:{id:'sub_fixture',customer:{id:'cus_fixture'},status:'active',cancel_at_period_end:true,items:{data:[{price:{id:'price_fixture'},current_period_end:2000000000}]}}}};
check(()=>assert.equal(lifecycleEvent(sub).p_period_end,new Date(2000000000000).toISOString()));
check(()=>assert.equal(lifecycleEvent(sub).p_cancel,true));
check(()=>assert.equal(lifecycleEvent(sub).p_price,'price_fixture'));
sub.type='customer.subscription.deleted';check(()=>assert.equal(lifecycleEvent(sub).p_status,'canceled'));
console.log(`${n} lifecycle payload checks passed`);
